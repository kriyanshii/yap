// scene text (plurals are caught by the stem matcher). A guess is right when it names every object and every color.
// Each hint is what the Yapper sees after pressing "Hint": the scene without the banned words, and phrases the
// artist understood on the scenic bench. Those phrases avoid the misses: "in the sky" with no "at the top",
