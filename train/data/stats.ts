// Renders train/data/stats.md. Deterministic for a given seed (no timestamps).
import { CATEGORY_WEIGHTS, EMPTY_REASONS, type Category } from './intents.ts';
import type { LeakReport } from './leakage.ts';
import type { Example, GenResult } from './generator.ts';
import { Rng } from './rng.ts';

const pct = (k: number, n: number) => (n ? `${((100 * k) / n).toFixed(1)}%` : '-');
const count = <T>(xs: T[], f: (x: T) => string | null) => {
  const m = new Map<string, number>();
  for (const x of xs) { const k = f(x); if (k !== null) m.set(k, (m.get(k) ?? 0) + 1); }
  return m;
};
const table = (head: string[], rows: (string | number)[][]) =>
  [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map(r => `| ${r.join(' | ')} |`)].join('\n');

function scene(ex: Example): string {
  const objs = ex.input.scene.objects.map(o => `${o.id}(${o.color}, ${o.x},${o.y}${o.scale !== 1 ? `, x${o.scale}` : ''})`).join(' ');
  return `${objs || '(empty)'}; focus=${ex.input.focus_id ?? 'null'}; history=${ex.input.history_len}`;
}

export function renderStats(res: GenResult, leak: LeakReport, benchCount: number, cmd: string): string {
  const { train, val, drops } = res;
  const all = [...train, ...val];
  const cats = Object.keys(CATEGORY_WEIGHTS) as Category[];
  const byCat = (xs: Example[]) => count(xs, e => e.meta.category);
  const trC = byCat(train), vaC = byCat(val);
  const reasons = count(all, e => e.meta.reason);
  const emptyN = all.filter(e => e.ops.length === 0).length;
  const para = all.filter(e => e.meta.paraphrased);
  const noisy = all.filter(e => e.meta.noise.length);
  const mishear = all.filter(e => e.meta.mishear);
  const noiseKinds = count(all.flatMap(e => e.meta.noise), n => n);
  const rules = count(para.flatMap(e => e.meta.paraphrase_rules), r => r);
  const subtypes = [...count(all, e => e.meta.subtype)].sort((a, b) => b[1] - a[1]);
  const leakTotal = Object.values(drops.leak).reduce((s, v) => s + v, 0);

  const rng = new Rng(res.seed + 1);
  const samples = rng.sample(train, 20);

  return `# Yap SFT data stats

Generated by \`${cmd}\` (seed ${res.seed}). Same command, same files.

- train: **${train.length}**, val: **${val.length}**
- should-return-[]: **${emptyN}** (${pct(emptyN, all.length)}) — the 30% \`empty\` category plus vague indirect descriptions
- paraphrased: **${para.length}** (${pct(para.length, all.length)}), all by \`${[...new Set(para.map(e => e.meta.paraphrase_model))].join(', ') || '-'}\` (deterministic rules; no LLM was used)
- noisy: **${noisy.length}** (${pct(noisy.length, all.length)}); with a mishear: ${mishear.length} (${pct(mishear.length, all.length)})
- policy: ${all.filter(e => e.meta.policy === 'strict').length} strict, ${all.filter(e => e.meta.policy === 'inferred').length} inferred (indirect + repaired mishears)
- formatted (capitalized, punctuated): ${all.filter(e => e.meta.formatted).length}

## Categories
${table(['category', 'target', 'train', 'train %', 'val'], cats.map(c => [c, pct(CATEGORY_WEIGHTS[c], 1), trC.get(c) ?? 0, pct(trC.get(c) ?? 0, train.length), vaC.get(c) ?? 0]))}

## [] reasons (train + val)
${table(['reason', 'n', 'checked by'], EMPTY_REASONS.map(r => [r, reasons.get(r) ?? 0, all.find(e => e.meta.reason === r)?.meta.verified_by ?? '-']))}

"engine": the ops a mapper would emit if it ignored the problem were run on \`src/scene/engine.ts\` and rejected. "construction": the reason holds by how the case is built (unsupported word in the text, focus_id null, hand-labeled vague description, chatter pool).

## Subtypes (train + val)
${table(['subtype', 'n'], subtypes)}

## Noise and paraphrase
${table(['noise op', 'n'], [...noiseKinds].sort((a, b) => b[1] - a[1]))}

${table(['paraphrase rule', 'n'], [...rules].sort((a, b) => b[1] - a[1]))}

## Filtering
- candidates rejected by the leakage filter (edit distance <= 5 to a benchmark utterance): **${leakTotal}** (${cats.map(c => `${c} ${drops.leak[c] ?? 0}`).join(', ')})
- near-duplicates dropped (same normalized utterance + scene + focus + history): ${drops.duplicate}
- val candidates dropped because the utterance is already in train: ${drops.val_overlaps_train}
- paraphrases rejected for changing a slot word: ${drops.paraphrase_rejected}
- intents unsatisfiable on the sampled scene (resampled): ${drops.unsatisfiable}

## Leakage check
- checked ${leak.checked} utterances (train + val) against ${benchCount} v1 + v2 benchmark utterances
- within edit distance 5: **${leak.leaks.length}** → ${leak.leaks.length ? 'FAIL' : 'PASS'}
- closest pair: distance ${leak.minDistance}: "${leak.closest?.utterance}" vs ${leak.closest?.bench}

## 20 random train samples
${samples.map((e, i) => `${i + 1}. **${e.meta.subtype.startsWith(`${e.meta.category}/`) ? e.meta.subtype : `${e.meta.category}/${e.meta.subtype}`}**${e.meta.reason ? ` [] ${e.meta.reason}` : ''}${e.meta.paraphrased ? ` · paraphrased (${e.meta.paraphrase_rules.join('+')})` : ''}${e.meta.noise.length ? ` · noise: ${e.meta.noise.join(', ')}` : ''}
   - utterance: \`${e.input.utterance}\`${e.meta.template !== e.input.utterance ? `  (template: \`${e.meta.template}\`)` : ''}
   - scene: ${scene(e)}
   - ops: \`${JSON.stringify(e.ops)}\``).join('\n')}
`;
}
